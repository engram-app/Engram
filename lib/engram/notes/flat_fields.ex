defmodule Engram.Notes.FlatFields do
  @moduledoc """
  The v5 first-class frontmatter fields (spec 3.3b, flat schema approved
  2026-10-20), extracted ONCE per indexing pass and written to two sinks:
  the `notes` columns and `note_attrs` rows (Postgres, the source of truth)
  and the v5 Qdrant payload (a derived copy).

  Our own FLAT keys; OKF's nested forms are read only as aliases, and the
  flat key wins when a note has both. `type` and `tags` are not here: their
  blind indexes already live on the note row (`type_hmac`, `tags_hmac`).

  Dates are ISO dates or datetimes. A bare date is midnight UTC for the flat
  keys; the nested aliases (`generated.at`, `verified[].at`, `stale_after`)
  need a full datetime with an offset, as OKF requires. Nothing here writes
  back into the user's frontmatter. Values are never logged.

  `fm_updated` uses the v5 precedence (`updated` first). The older
  `notes.fm_timestamp` keeps OKF's (`generated.at`, then `timestamp`); the two
  differ only for a note that sets conflicting keys.
  """

  alias Engram.Crypto
  alias Engram.Crypto.Envelope
  alias Engram.Notes.Frontmatter
  alias Engram.Notes.FrontmatterAttrs
  alias Engram.Notes.OkfFields
  alias Engram.Vector.FilterId

  @max_string 256
  @max_list 64

  @updated [
    {~w(updated), :lenient},
    {~w(generated at), :strict},
    {~w(timestamp), :lenient},
    {~w(modified), :lenient}
  ]
  @created [{~w(created), :lenient}, {~w(date), :lenient}]
  @expires [{~w(expires), :lenient}, {~w(stale_after), :strict}]

  @type t :: %{
          status: String.t() | nil,
          author: String.t() | nil,
          reviewed_by: String.t() | nil,
          project: String.t() | nil,
          source: [String.t()],
          status_hmac: binary() | nil,
          author_hmac: binary() | nil,
          rev_by_hmac: binary() | nil,
          proj_hmac: binary() | nil,
          src_hmac: [binary()],
          fm_updated: integer() | nil,
          fm_created: integer() | nil,
          fm_reviewed: integer() | nil,
          fm_expires: integer() | nil,
          fm_due: integer() | nil,
          fm_priority: float() | nil,
          attrs: [map()],
          nums: [map()],
          dates: [map()]
        }

  @empty %{
    status: nil,
    author: nil,
    reviewed_by: nil,
    project: nil,
    source: [],
    status_hmac: nil,
    author_hmac: nil,
    rev_by_hmac: nil,
    proj_hmac: nil,
    src_hmac: [],
    fm_updated: nil,
    fm_created: nil,
    fm_reviewed: nil,
    fm_expires: nil,
    fm_due: nil,
    fm_priority: nil,
    attrs: [],
    nums: [],
    dates: []
  }

  # No @spec on the constant accessors: dialyzer's :underspecs flags any
  # spec wider than the literal.
  def empty, do: @empty

  @doc "Fields from a note's plaintext content (nil content gives `empty/0`)."
  @spec extract(String.t() | nil, binary()) :: t()
  def extract(content, filter_key) when is_binary(content) do
    case Frontmatter.split(content) do
      {block, _body} when is_binary(block) ->
        block |> Frontmatter.parse() |> OkfFields.values() |> from_values(filter_key)

      _ ->
        @empty
    end
  end

  def extract(nil, _filter_key), do: @empty

  defp from_values(values, _filter_key) when values == %{}, do: @empty

  defp from_values(v, fk) do
    {verified_by, verified_at} = latest_verified(v["verified"])

    status = str(v["status"])
    author = str(v["author"]) || str(dig(v, ~w(generated by)))
    reviewed_by = str(v["reviewed_by"]) || verified_by
    project = str(v["project"])
    source = strs(v["source"]) || strs(v["resource"]) || strs(v["sources"]) || []

    Map.merge(FrontmatterAttrs.extract(v, fk), %{
      status: status,
      author: author,
      reviewed_by: reviewed_by,
      project: project,
      source: source,
      status_hmac: hmac(fk, status),
      author_hmac: hmac(fk, author),
      rev_by_hmac: hmac(fk, reviewed_by),
      proj_hmac: hmac(fk, project),
      src_hmac: Enum.map(source, &FilterId.value_hmac(fk, &1)),
      fm_updated: unix(OkfFields.first_date(v, @updated)),
      fm_created: unix(OkfFields.first_date(v, @created)),
      fm_reviewed: unix(OkfFields.parse_date_value(v["reviewed"], :lenient)) || verified_at,
      fm_expires: unix(OkfFields.first_date(v, @expires)),
      fm_due: unix(OkfFields.parse_date_value(v["due"], :lenient)),
      fm_priority: if(is_number(v["priority"]), do: v["priority"] / 1)
    })
  end

  @doc """
  The `notes` columns for `flat`: blind indexes and plaintext numbers as
  stored, exact values encrypted under `dek` with AAD
  `aad_for_row(:notes, <field>, note_id)` (`source` as one JSON list). Every
  column is present, so an absent key clears what an earlier pass stored.
  """
  @spec columns(t(), <<_::256>>, Ecto.UUID.t()) :: keyword()
  def columns(flat, dek, note_id) do
    source = if flat.source != [], do: Jason.encode!(flat.source)

    [
      status_hmac: flat.status_hmac,
      author_hmac: flat.author_hmac,
      rev_by_hmac: flat.rev_by_hmac,
      proj_hmac: flat.proj_hmac,
      src_hmac: if(flat.src_hmac != [], do: flat.src_hmac),
      fm_updated: flat.fm_updated,
      fm_reviewed: flat.fm_reviewed,
      fm_expires: flat.fm_expires,
      fm_due: flat.fm_due,
      fm_priority: flat.fm_priority
    ] ++
      envelope(dek, note_id, :status, flat.status) ++
      envelope(dek, note_id, :author, flat.author) ++
      envelope(dek, note_id, :reviewed_by, flat.reviewed_by) ++
      envelope(dek, note_id, :project, flat.project) ++
      envelope(dek, note_id, :source, source)
  end

  @doc "The `note_attrs` rows for `flat` (one per long-tail value)."
  @spec attr_rows(t(), %{id: Ecto.UUID.t(), user_id: Ecto.UUID.t()}) :: [map()]
  def attr_rows(flat, %{id: note_id, user_id: user_id}) do
    row = &Map.merge(%{note_id: note_id, user_id: user_id, key_hmac: &1}, &2)

    for(%{k: k, v: v} <- flat.attrs, do: row.(k, %{value_hmac: v})) ++
      for(%{k: k, n: n} <- flat.nums, do: row.(k, %{value_num: n})) ++
      for(%{k: k, t: t} <- flat.dates, do: row.(k, %{value_date: t}))
  end

  # Explicit atoms per field (no runtime atom building).
  @envelope_keys %{
    status: {:status_ciphertext, :status_nonce},
    author: {:author_ciphertext, :author_nonce},
    reviewed_by: {:reviewed_by_ciphertext, :reviewed_by_nonce},
    project: {:project_ciphertext, :project_nonce},
    source: {:source_ciphertext, :source_nonce}
  }

  @doc "The `{ciphertext, nonce}` column names of each encrypted flat field."
  def envelope_keys, do: @envelope_keys

  defp envelope(dek, note_id, field, value) do
    {ct_key, nonce_key} = Map.fetch!(@envelope_keys, field)

    {ct, nonce} =
      if value,
        do: Envelope.encrypt(value, dek, Crypto.aad_for_row(:notes, field, note_id)),
        else: {nil, nil}

    [{ct_key, ct}, {nonce_key, nonce}]
  end

  # OKF `verified` is a list of `{by, at}`; the most recent entry with a
  # valid strict `at` answers both aliases, else the last entry's `by`.
  defp latest_verified(list) when is_list(list) do
    entries =
      for %{} = e <- list, do: {str(e["by"]), unix(OkfFields.parse_date_value(e["at"], :strict))}

    case Enum.filter(entries, &elem(&1, 1)) do
      [] -> {entries |> List.last() |> then(&(&1 && elem(&1, 0))), nil}
      dated -> Enum.max_by(dated, &elem(&1, 1))
    end
  end

  defp latest_verified(_), do: {nil, nil}

  defp dig(v, [a, b]), do: is_map(v[a]) && v[a][b]

  defp str(s) when is_binary(s) and s != "" and byte_size(s) <= @max_string, do: s
  defp str(_), do: nil

  defp strs(list) when is_list(list) do
    case list |> Enum.take(@max_list) |> Enum.map(&str/1) |> Enum.reject(&is_nil/1) do
      [] -> nil
      kept -> kept
    end
  end

  defp strs(s), do: if(str(s), do: [s])

  defp hmac(_fk, nil), do: nil
  defp hmac(fk, s), do: FilterId.value_hmac(fk, s)

  defp unix(nil), do: nil
  defp unix(%DateTime{} = dt), do: DateTime.to_unix(dt)
end
