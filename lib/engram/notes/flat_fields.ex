defmodule Engram.Notes.FlatFields do
  @moduledoc """
  The v5 frontmatter filter fields (spec 3.3b, flat schema approved
  2026-10-20), extracted ONCE per indexing pass and written to two sinks:
  `note_attrs` rows (Postgres, the source of truth; `notes` itself gets no
  columns, per the 2026-10-20 Postgres scale audit) and the v5 Qdrant payload
  (a derived copy). The named fields take the reserved key ids of
  `Engram.Notes.FrontmatterKeys`; user-added keys get dictionary ids
  (`put_key_ids/2`).

  Our own FLAT keys; OKF's nested forms are read only as aliases, and the
  flat key wins when a note has both. `type` and `tags` are not here: their
  blind indexes already live on the note row (`type_hmac`, `tags_hmac`).

  Dates are parsed by `FrontmatterDate` (ISO and Obsidian forms). A bare date
  is midnight UTC for the flat keys; the nested aliases (`generated.at`,
  `verified[].at`, `stale_after`) need a datetime with an offset, as OKF
  requires. `due`/`expires` keep the day as written. Keys match
  case-insensitively, and a localized key name is its English field
  (`種類` is `type`; `Engram.Notes.KeyAliases`, applied by
  `OkfFields.values/1`, with its collision rule). Nothing here writes
  back into the user's frontmatter. Values are never logged.

  `fm_updated` uses the v5 precedence (`updated` first). The older
  `notes.fm_timestamp` keeps OKF's (`generated.at`, then `timestamp`); the two
  differ only for a note that sets conflicting keys.
  """

  alias Engram.Notes.Frontmatter
  alias Engram.Notes.FrontmatterAttrs
  alias Engram.Notes.FrontmatterDate
  alias Engram.Notes.FrontmatterKeys
  alias Engram.Notes.OkfFields
  alias Engram.Vector.FilterId

  @max_string 256
  @max_list 64

  @updated [
    {~w(updated), :lenient},
    {~w(generated at), :strict},
    {~w(timestamp), :lenient},
    {~w(modified), :lenient}
  ]
  @created [{~w(created), :lenient}, {~w(date), :lenient}]
  @expires [{~w(expires), :lenient}, {~w(stale_after), :strict}]

  @type t :: %{
          status: String.t() | nil,
          author: String.t() | nil,
          reviewed_by: String.t() | nil,
          project: String.t() | nil,
          source: [String.t()],
          status_hmac: binary() | nil,
          author_hmac: binary() | nil,
          rev_by_hmac: binary() | nil,
          proj_hmac: binary() | nil,
          src_hmac: [binary()],
          fm_updated: integer() | nil,
          fm_created: integer() | nil,
          fm_reviewed: integer() | nil,
          fm_expires: integer() | nil,
          fm_due: integer() | nil,
          fm_priority: float() | nil,
          attrs: [map()],
          nums: [map()],
          dates: [map()],
          names: %{binary() => String.t()},
          key_ids: %{binary() => integer()}
        }

  @empty %{
    status: nil,
    author: nil,
    reviewed_by: nil,
    project: nil,
    source: [],
    status_hmac: nil,
    author_hmac: nil,
    rev_by_hmac: nil,
    proj_hmac: nil,
    src_hmac: [],
    fm_updated: nil,
    fm_created: nil,
    fm_reviewed: nil,
    fm_expires: nil,
    fm_due: nil,
    fm_priority: nil,
    attrs: [],
    nums: [],
    dates: [],
    names: %{},
    key_ids: %{}
  }

  # No @spec on the constant accessors: dialyzer's :underspecs flags any
  # spec wider than the literal.
  def empty, do: @empty

  @doc "Fields from a note's plaintext content (nil content gives `empty/0`)."
  @spec extract(String.t() | nil, binary()) :: t()
  def extract(content, filter_key) when is_binary(content) do
    case Frontmatter.split(content) do
      {block, _body} when is_binary(block) ->
        block |> Frontmatter.parse() |> OkfFields.values() |> from_values(filter_key)

      _ ->
        @empty
    end
  end

  def extract(nil, _filter_key), do: @empty

  defp from_values(values, _filter_key) when values == %{}, do: @empty

  defp from_values(values, fk) do
    v = lower_keys(values)
    {verified_by, verified_at} = latest_verified(v["verified"])

    status = str(v["status"])
    author = str(v["author"]) || str(dig(v, ~w(generated by)))
    reviewed_by = str(v["reviewed_by"]) || verified_by
    project = str(v["project"])
    source = strs(v["source"]) || strs(v["resource"]) || strs(v["sources"]) || []

    # The long tail from the keys as written (the HMAC folds case), so the
    # dictionary keeps the user's spelling.
    Map.merge(FrontmatterAttrs.extract(values, fk), %{
      key_ids: %{},
      status: status,
      author: author,
      reviewed_by: reviewed_by,
      project: project,
      source: source,
      status_hmac: hmac(fk, status),
      author_hmac: hmac(fk, author),
      rev_by_hmac: hmac(fk, reviewed_by),
      proj_hmac: hmac(fk, project),
      src_hmac: Enum.map(source, &FilterId.value_hmac(fk, &1)),
      fm_updated: instant(first_date(v, @updated)),
      fm_created: instant(first_date(v, @created)),
      fm_reviewed: instant(FrontmatterDate.parse(v["reviewed"], :lenient)) || verified_at,
      fm_expires: written_day(first_date(v, @expires)),
      fm_due: written_day(FrontmatterDate.parse(v["due"], :lenient)),
      fm_priority: FrontmatterAttrs.number(v["priority"])
    })
  end

  @doc "`flat` with the dictionary ids of its user-added keys (`FrontmatterKeys.resolve/3`)."
  @spec put_key_ids(t(), %{binary() => integer()}) :: t()
  def put_key_ids(flat, key_ids), do: %{flat | key_ids: key_ids}

  @doc """
  The `note_attrs` rows for `flat`: one per value, `key_id`, `ord` (the
  value's position among its key's values, 0 for a scalar) and exactly one
  of `h` (exact, HMAC), `n` or `d`. The named fields use their reserved ids
  (`type`/`tags` from the note row's existing blind indexes); a user-added
  key without a dictionary id (past the cap) is left out, as in the payload.
  """
  @spec attr_rows(t(), map()) :: [map()]
  def attr_rows(flat, %{id: note_id, user_id: user_id, vault_id: vault_id} = note) do
    base = %{note_id: note_id, user_id: user_id, vault_id: vault_id}
    ids = flat.key_ids
    named = &FrontmatterKeys.named_id/1

    values =
      [
        {named.(:type), :h, [Map.get(note, :type_hmac)]},
        {named.(:tags), :h, Map.get(note, :tags_hmac) || []},
        {named.(:status), :h, [flat.status_hmac]},
        {named.(:author), :h, [flat.author_hmac]},
        {named.(:reviewed_by), :h, [flat.rev_by_hmac]},
        {named.(:source), :h, flat.src_hmac},
        {named.(:project), :h, [flat.proj_hmac]},
        {named.(:created), :d, [flat.fm_created]},
        {named.(:updated), :d, [flat.fm_updated]},
        {named.(:reviewed), :d, [flat.fm_reviewed]},
        {named.(:expires), :d, [flat.fm_expires]},
        {named.(:due), :d, [flat.fm_due]},
        {named.(:priority), :n, [flat.fm_priority]}
      ]
      |> Enum.flat_map(fn {id, col, vs} -> for v <- vs, v != nil, do: {id, col, v} end)

    user =
      for(%{k: k, v: v} <- flat.attrs, Map.has_key?(ids, k), do: {ids[k], :h, v}) ++
        for(%{k: k, n: n} <- flat.nums, Map.has_key?(ids, k), do: {ids[k], :n, n}) ++
        for %{k: k, t: t} <- flat.dates, Map.has_key?(ids, k), do: {ids[k], :d, t}

    (values ++ user)
    |> Enum.group_by(&elem(&1, 0))
    |> Enum.flat_map(fn {key_id, entries} ->
      entries
      |> Enum.with_index()
      |> Enum.map(fn {{_id, col, v}, ord} ->
        Map.merge(base, %{key_id: key_id, ord: ord, h: nil, n: nil, d: nil})
        |> Map.put(col, v)
      end)
    end)
  end

  # OKF `verified` is a list of `{by, at}`; the most recent entry with a
  # valid strict `at` answers both aliases, else the last entry's `by`.
  defp latest_verified(list) when is_list(list) do
    entries =
      for %{} = e <- list, do: {str(e["by"]), instant(FrontmatterDate.parse(e["at"], :strict))}

    case Enum.filter(entries, &elem(&1, 1)) do
      [] -> {entries |> List.last() |> then(&(&1 && elem(&1, 0))), nil}
      dated -> Enum.max_by(dated, &elem(&1, 1))
    end
  end

  defp latest_verified(_), do: {nil, nil}

  defp dig(v, [a, b]), do: if(is_map(v[a]), do: v[a][b])

  # YAML reads `status: 2` as a number and `reviewed_by: true` as a boolean;
  # a named exact field holds their text, so a filter for "2" finds them.
  defp str(s) when is_binary(s) and s != "" and byte_size(s) <= @max_string, do: s
  defp str(scalar) when is_number(scalar) or is_boolean(scalar), do: str(to_string(scalar))
  defp str(_), do: nil

  defp strs(list) when is_list(list) do
    case list |> Enum.take(@max_list) |> Enum.map(&str/1) |> Enum.reject(&is_nil/1) do
      [] -> nil
      kept -> kept
    end
  end

  defp strs(s), do: if(text = str(s), do: [text])

  defp hmac(_fk, nil), do: nil
  defp hmac(fk, s), do: FilterId.value_hmac(fk, s)

  defp first_date(v, aliases),
    do:
      Enum.find_value(aliases, fn {path, mode} ->
        FrontmatterDate.parse(dig_path(v, path), mode)
      end)

  defp dig_path(v, [key]), do: v[key]
  defp dig_path(v, [a, b]), do: dig(v, [a, b])

  defp instant(nil), do: nil
  defp instant({unix, _date}), do: unix

  # Date-only fields keep the day as WRITTEN, stored as that day's midnight
  # UTC so `div(fm_due, 86_400)` is the payload's day number.
  defp written_day(nil), do: nil
  defp written_day({_unix, date}), do: FrontmatterDate.day(date) * 86_400

  # Keys match case-insensitively (`Status:` is `status`), at every level so
  # the nested aliases (`Generated: {By: x}`) match too. When two keys fold
  # together, the one already written in lowercase wins.
  defp lower_keys(%{} = map) do
    map
    |> Enum.sort_by(fn {k, _} -> k == String.downcase(k) end)
    |> Map.new(fn {k, val} -> {String.downcase(k), lower_keys(val)} end)
  end

  defp lower_keys(list) when is_list(list), do: Enum.map(list, &lower_keys/1)
  defp lower_keys(other), do: other
end
